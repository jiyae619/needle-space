#!/usr/bin/env node
/**
 * One-shot backfill: rewrite cafes.productivity_score using Strategy C
 * (LLM-first, regex fallback) so the persisted score matches what the
 * UI shows on the card, breakdown, and chips.
 *
 * Uses scripts/_shared.mjs, which is tested against src/lib/score.ts.
 *
 * Usage:
 *   node scripts/recompute-merged-scores.mjs           # live update
 *   node scripts/recompute-merged-scores.mjs --dry-run # preview only
 *
 * Outputs a markdown table of every cafe whose score changed to
 * docs/SCORE-UPDATE.md (and stdout).
 */

import { createClient } from "@supabase/supabase-js";
import { writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { env } from "./_env.mjs";
import { computeMergedScore } from "./_shared.mjs";

if (!env.NEXT_PUBLIC_SUPABASE_URL || !env.SUPABASE_SERVICE_ROLE_KEY) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY (set them in the environment or .env.local)");
  process.exit(1);
}
const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);

const DRY_RUN = process.argv.includes("--dry-run");

console.log(`🧮 Recomputing productivity_score from Strategy C merged values`);
console.log(`   Mode: ${DRY_RUN ? "DRY RUN — preview only" : "LIVE — writing to DB"}\n`);

const { data: cafes, error } = await supabase
  .from("cafes")
  .select("id, name, neighborhood, google_rating, productivity_score, " +
    "wifi_quality, outlet_availability, noise_level, laptop_policy, seating_availability, " +
    "wifi_quality_llm, outlet_availability_llm, noise_level_llm, laptop_policy_llm, seating_availability_llm")
  .order("name");

if (error) { console.error("Supabase error:", error.message); process.exit(1); }
console.log(`Loaded ${cafes.length} cafes.\n`);

const changed = [];
let unchanged = 0, skipped = 0;

for (const cafe of cafes) {
  const next = computeMergedScore(cafe);
  if (next == null) { skipped++; continue; }
  const prev = cafe.productivity_score;
  if (prev != null && Math.abs(next - prev) < 0.05) { unchanged++; continue; }

  changed.push({
    id: cafe.id,
    name: cafe.name,
    neighborhood: cafe.neighborhood,
    prev,
    next,
    delta: prev != null ? Math.round((next - prev) * 10) / 10 : null,
  });

  if (!DRY_RUN) {
    const { error: upErr } = await supabase
      .from("cafes")
      .update({ productivity_score: next })
      .eq("id", cafe.id);
    if (upErr) console.error(`  ⚠️  ${cafe.name}: ${upErr.message}`);
  }
}

console.log(`━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`);
console.log(`Changed:    ${changed.length}`);
console.log(`Unchanged:  ${unchanged}`);
console.log(`Skipped:    ${skipped} (no signal at all)`);
console.log(``);

// Sort changes by absolute delta descending
changed.sort((a, b) => Math.abs(b.delta ?? 0) - Math.abs(a.delta ?? 0));

const lines = [];
lines.push(`<!-- Auto-generated by scripts/recompute-merged-scores.mjs -->`);
lines.push(``);
lines.push(`# Productivity score backfill — merged LLM + regex`);
lines.push(``);
lines.push(`Run: ${new Date().toISOString().slice(0, 10)} · ${DRY_RUN ? "DRY RUN" : "LIVE"}`);
lines.push(``);
lines.push(`Cafes updated: **${changed.length}** of ${cafes.length}.`);
lines.push(`(Unchanged: ${unchanged}; skipped — no signal at all: ${skipped}.)`);
lines.push(``);
lines.push(`| Cafe | Neighborhood | Was | Now | Δ |`);
lines.push(`|---|---|---:|---:|---:|`);
for (const c of changed) {
  const wasStr = c.prev == null ? "—" : c.prev.toFixed(1);
  const dStr = c.delta == null ? "new" : (c.delta > 0 ? `+${c.delta.toFixed(1)}` : c.delta.toFixed(1));
  lines.push(`| ${c.name} | ${c.neighborhood ?? "—"} | ${wasStr} | ${c.next.toFixed(1)} | ${dStr} |`);
}
const md = lines.join("\n") + "\n";

const outPath = resolve("docs/SCORE-UPDATE.md");
if (!DRY_RUN) {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, md);
  console.log(`Wrote ${outPath}`);
}
// Also echo to stdout for terminal review
console.log("");
console.log(md);
